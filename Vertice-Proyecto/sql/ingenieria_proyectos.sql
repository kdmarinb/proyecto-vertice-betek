--  DDL – Creación de tablas

CREATE TABLE CLIENTES (
    id_cliente   INT           NOT NULL AUTO_INCREMENT,
    nombre       VARCHAR(100)  NOT NULL,
    empresa      VARCHAR(120)  NOT NULL,
    contacto     VARCHAR(15)   NOT NULL,
    ciudad       VARCHAR(60),
    nit          VARCHAR(20),
    email        VARCHAR(100),
    PRIMARY KEY (id_cliente)
) ENGINE=InnoDB;

CREATE TABLE EMPLEADOS (
    id_empleado       INT          NOT NULL AUTO_INCREMENT,
    nombre            VARCHAR(100) NOT NULL,
    cargo             VARCHAR(80)  NOT NULL,
    especialidad      VARCHAR(60)  NOT NULL,
    experiencia_anios INT          NOT NULL DEFAULT 0,
    formacion         VARCHAR(100),
    contacto          VARCHAR(15),
    cedula            VARCHAR(12)  UNIQUE,
    ciudad            VARCHAR(60),
    PRIMARY KEY (id_empleado)
) ENGINE=InnoDB;

CREATE TABLE PROYECTOS (
    id_proyecto  INT             NOT NULL AUTO_INCREMENT,
    id_cliente   INT             NOT NULL,
    nombre       VARCHAR(150)    NOT NULL,
    descripcion  TEXT,
    fecha_inicio DATE            NOT NULL,
    fecha_fin    DATE            NOT NULL,
    presupuesto  DECIMAL(18,2)   NOT NULL DEFAULT 0,
    estado       VARCHAR(50)     NOT NULL DEFAULT 'En planeación',
    ciudad       VARCHAR(60),
    PRIMARY KEY (id_proyecto),
    CONSTRAINT fk_proy_cliente FOREIGN KEY (id_cliente)
        REFERENCES CLIENTES (id_cliente)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ETAPAS_PROYECTO (
    id_etapa     INT          NOT NULL AUTO_INCREMENT,
    id_proyecto  INT          NOT NULL,
    nombre_etapa VARCHAR(80)  NOT NULL,
    descripcion  TEXT,
    fecha_inicio DATE,
    fecha_fin    DATE,
    orden        INT          NOT NULL DEFAULT 1,
    PRIMARY KEY (id_etapa),
    CONSTRAINT fk_etapa_proy FOREIGN KEY (id_proyecto)
        REFERENCES PROYECTOS (id_proyecto)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE SPRINTS (
    id_sprint     INT          NOT NULL AUTO_INCREMENT,
    id_proyecto   INT          NOT NULL,
    fecha_inicio  DATE         NOT NULL,
    fecha_fin     DATE         NOT NULL,
    objetivo      VARCHAR(200),
    numero_sprint INT          NOT NULL DEFAULT 1,
    PRIMARY KEY (id_sprint),
    CONSTRAINT fk_sprint_proy FOREIGN KEY (id_proyecto)
        REFERENCES PROYECTOS (id_proyecto)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE HISTORIAS_USUARIO (
    id_historia  INT          NOT NULL AUTO_INCREMENT,
    id_sprint    INT          NOT NULL,
    descripcion  TEXT         NOT NULL,
    prioridad    VARCHAR(20)  NOT NULL DEFAULT 'Media',
    story_points INT          NOT NULL DEFAULT 1,
    estado       VARCHAR(50)  NOT NULL DEFAULT 'Pendiente',
    PRIMARY KEY (id_historia),
    CONSTRAINT fk_hist_sprint FOREIGN KEY (id_sprint)
        REFERENCES SPRINTS (id_sprint)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE TAREAS (
    id_tarea         INT           NOT NULL AUTO_INCREMENT,
    id_historia      INT           NOT NULL,
    id_empleado      INT           NOT NULL,
    rol              VARCHAR(60),
    horas_estimadas  DECIMAL(6,1)  NOT NULL DEFAULT 0,
    horas_reales     DECIMAL(6,1)           DEFAULT 0,
    estado           VARCHAR(50)   NOT NULL DEFAULT 'Pendiente',
    descripcion      TEXT,
    PRIMARY KEY (id_tarea),
    CONSTRAINT fk_tarea_hist FOREIGN KEY (id_historia)
        REFERENCES HISTORIAS_USUARIO (id_historia)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_tarea_emp FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADOS (id_empleado)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE RECURSOS (
    id_recurso     INT            NOT NULL AUTO_INCREMENT,
    nombre         VARCHAR(100)   NOT NULL,
    tipo           VARCHAR(50)    NOT NULL,
    costo_unitario DECIMAL(14,2)  NOT NULL DEFAULT 0,
    unidad_medida  VARCHAR(20),
    PRIMARY KEY (id_recurso)
) ENGINE=InnoDB;

CREATE TABLE ASIGNACION_RECURSOS (
    id_asignacion    INT            NOT NULL AUTO_INCREMENT,
    id_proyecto      INT            NOT NULL,
    id_recurso       INT            NOT NULL,
    cantidad         DECIMAL(10,2)  NOT NULL DEFAULT 1,
    costo_calculado  DECIMAL(18,2)  NOT NULL DEFAULT 0,
    fecha_asignacion DATE,
    PRIMARY KEY (id_asignacion),
    CONSTRAINT fk_asig_proy FOREIGN KEY (id_proyecto)
        REFERENCES PROYECTOS (id_proyecto)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_asig_rec FOREIGN KEY (id_recurso)
        REFERENCES RECURSOS (id_recurso)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE COSTOS (
    id_costo    INT            NOT NULL AUTO_INCREMENT,
    id_proyecto INT            NOT NULL,
    categoria   VARCHAR(60)    NOT NULL,
    descripcion TEXT,
    valor       DECIMAL(18,2)  NOT NULL DEFAULT 0,
    fecha       DATE           NOT NULL,
    PRIMARY KEY (id_costo),
    CONSTRAINT fk_costo_proy FOREIGN KEY (id_proyecto)
        REFERENCES PROYECTOS (id_proyecto)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

